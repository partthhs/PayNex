def seed_database(db: Session) -> None:
    """Seed categories and products. Inserts new or updates existing products."""
    print("[Seeder] Checking categories...")
    cat_map = {}
    for c in CATEGORIES:
        existing = db.query(Category).filter(Category.slug == c["slug"]).first()
        if not existing:
            cat = Category(**c)
            db.add(cat)
            db.flush()
            cat_map[c["slug"]] = cat.id
        else:
            cat_map[c["slug"]] = existing.id

    print(f"[Seeder] Syncing {len(PRODUCTS)} products across all categories...")
    for p_data in PRODUCTS:
        p = dict(p_data)
        cat_slug = p.pop("category_slug")
        category_id = cat_map[cat_slug]

        existing_prod = db.query(Product).filter(Product.slug == p["slug"]).first()
        if existing_prod:
            # Update attributes
            existing_prod.name = p["name"]
            existing_prod.brand = p["brand"]
            existing_prod.category_id = category_id
            existing_prod.price = p["price"]
            existing_prod.original_price = p["original_price"]
            existing_prod.rating = p["rating"]
            existing_prod.reviews_count = p["reviews_count"]
            existing_prod.image_url = p["image_url"]
            existing_prod.description = p["description"]
            existing_prod.short_description = p["short_description"]
            existing_prod.features = p["features"]
            existing_prod.specs = p["specs"]
            existing_prod.badge = p["badge"]
            existing_prod.in_stock = p["in_stock"]
        else:
            prod = Product(**p, category_id=category_id)
            db.add(prod)

    db.commit()
    count = db.query(Product).count()
    print(f"[Seeder] Completed! Database now contains {count} products.")
